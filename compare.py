#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""เครื่องผลิตโจทย์ "การเปรียบเทียบเชิงปริมาณ" — แนวย่อยของ TGAT2 ท่อนความสามารถทางจำนวน

รูปแบบจากข้อสอบจริง (`reference/tgat2/DIGEST.md` และ `TGAT2 Dek66.pdf` หน้า 9):
ให้ข้อมูล 3 สดมภ์ ก. ข. ค. แต่ละสดมภ์คำนวณได้เป็นปริมาณหนึ่ง แล้วเลือกตอบจากตัวเลือกคงที่ 5 ข้อ

    1) สดมภ์ ก. มากที่สุด   2) สดมภ์ ข. มากที่สุด   3) สดมภ์ ค. มากที่สุด
    4) ทั้ง 3 สดมภ์เท่ากัน   5) ข้อมูลไม่เพียงพอที่จะเปรียบเทียบ

**กับดักที่ต้องกันให้ได้** — ตัวเลือกที่ 4 คือ *ทั้งสาม* เท่ากัน ไม่ใช่ *สอง* เท่ากัน
ถ้าสุ่มแล้วบังเอิญได้สองสดมภ์เสมอกันที่ตำแหน่งสูงสุด **โจทย์นั้นจะไม่มีคำตอบเลย**
ตัวตรวจด้านล่างบังคับว่าต้องเข้าเงื่อนไขใดเงื่อนไขหนึ่งเท่านั้น: มีตัวมากสุดตัวเดียวชัดเจน หรือเท่ากันหมดทั้งสาม

คำนวณด้วย Decimal ความละเอียด 60 หลัก **ไม่ใช้ float** เพราะแนวนี้ต้องตัดสินว่า "เท่ากันไหม"
ตัวอย่างจริงที่ float ทำพลาด: sin60°×cos60° กับ sin30°×cos30° เท่ากันพอดีทั้งคู่ (= √3/4)
แต่ float ให้ 0.4330127018922194 กับ 0.4330127018922193 ต่างกันที่หลักที่ 16
ถ้าใช้ float โจทย์แบบนี้จะได้เฉลย "ก. มากที่สุด" แทน "เท่ากันทั้งสาม" = เฉลยผิดหลุดถึงมือนักเรียน
"""
from decimal import Decimal as D, getcontext

getcontext().prec = 60

PI = D("3.14159265358979323846264338327950288419716939937510582097494")
SQRT3 = D(3).sqrt()

# ห่างกันน้อยกว่านี้ = ถือว่าเท่ากัน · ห่างกันมากกว่านี้ = ถือว่าต่างกันชัดเจน
# ช่วงระหว่างสองค่านี้คือเขตอันตราย เจอเมื่อไหร่ให้ทิ้งโจทย์ทิ้ง
EPS_EQ = D("1e-40")
EPS_DIFF = D("1e-12")

CHOICES = [
    "ปริมาณในสดมภ์ ก. มากที่สุด",
    "ปริมาณในสดมภ์ ข. มากที่สุด",
    "ปริมาณในสดมภ์ ค. มากที่สุด",
    "ปริมาณทั้ง 3 สดมภ์เท่ากัน",
    "ข้อมูลที่กำหนดให้ไม่เพียงพอที่จะเปรียบเทียบ",
]

STEM = ("ข้อมูลใน 3 สดมภ์ต่อไปนี้แต่ละสดมภ์คำนวณได้เป็นปริมาณหนึ่ง\n"
        "จงเปรียบเทียบปริมาณทั้งสามแล้วเลือกตอบ")


# ============================================================
#  โรงงานปริมาณ — แต่ละตัวคืน (ข้อความไทย, ค่าที่คำนวณได้)
# ============================================================

def q_percent(rng):
    a, b = rng.choice([10, 20, 25, 40, 50, 60, 80]), rng.choice([10, 20, 25, 40, 50, 60, 80])
    m, n = rng.choice([2000, 3000, 4000, 5000]), rng.choice([1000, 2000, 3000, 4000])
    txt = f"{a}% ของ {m:,} รวมกับ {b}% ของ {n:,}"
    return txt, D(a) * D(m) / 100 + D(b) * D(n) / 100


def q_circle(rng):
    r = rng.randint(3, 12)
    return f"พื้นที่ของวงกลมที่มีรัศมียาว {r} หน่วย", PI * D(r) ** 2


def q_square(rng):
    p = rng.choice([12, 16, 20, 24, 28, 32, 36, 40])
    return f"พื้นที่ของสี่เหลี่ยมจัตุรัสที่มีความยาวรอบรูป {p} หน่วย", (D(p) / 4) ** 2


def q_tri(rng):
    p = rng.choice([9, 12, 15, 18, 21, 24, 27, 30])
    s = D(p) / 3
    return f"พื้นที่ของสามเหลี่ยมด้านเท่าที่มีความยาวรอบรูป {p} หน่วย", SQRT3 / 4 * s ** 2


def q_rect(rng):
    w, h = rng.randint(3, 14), rng.randint(3, 14)
    return f"พื้นที่ของสี่เหลี่ยมมุมฉากกว้าง {w} หน่วย ยาว {h} หน่วย", D(w) * D(h)


def q_dice(rng):
    kind = rng.choice(["gt", "le", "even", "odd", "mult"])
    if kind == "gt":
        k = rng.randint(1, 4)
        n = 6 - k
        return f"ความน่าจะเป็นที่จะโยนลูกเต๋า 1 ลูก 1 ครั้ง แล้วได้แต้มมากกว่า {k}", D(n) / 6
    if kind == "le":
        k = rng.randint(2, 5)
        return f"ความน่าจะเป็นที่จะโยนลูกเต๋า 1 ลูก 1 ครั้ง แล้วได้แต้มไม่เกิน {k}", D(k) / 6
    if kind == "even":
        return "ความน่าจะเป็นที่จะโยนลูกเต๋า 1 ลูก 1 ครั้ง แล้วได้แต้มเป็นเลขคู่", D(3) / 6
    if kind == "odd":
        return "ความน่าจะเป็นที่จะโยนลูกเต๋า 1 ลูก 1 ครั้ง แล้วได้แต้มเป็นเลขคี่", D(3) / 6
    return "ความน่าจะเป็นที่จะโยนลูกเต๋า 1 ลูก 1 ครั้ง แล้วได้แต้มเป็นพหุคูณของ 3", D(2) / 6


# sin/cos ของมุมมาตรฐาน เก็บเป็นค่าที่แน่นอน ไม่ผ่าน float
_TRIG = {
    (30, "sin"): D(1) / 2,          (30, "cos"): SQRT3 / 2,
    (45, "sin"): D(2).sqrt() / 2,   (45, "cos"): D(2).sqrt() / 2,
    (60, "sin"): SQRT3 / 2,         (60, "cos"): D(1) / 2,
}


def q_trig(rng):
    a, b = rng.choice([30, 45, 60]), rng.choice([30, 45, 60])
    return f"sin {a}° × cos {b}°", _TRIG[(a, "sin")] * _TRIG[(b, "cos")]


def q_clock(rng):
    h, m = rng.randint(1, 12), rng.choice([0, 10, 15, 20, 30, 40, 45, 50])
    ang = abs(D(30) * (h % 12) + D(m) / 2 - D(6) * m)
    if ang > 180:
        ang = 360 - ang
    return f"ขนาดของมุมที่เข็มสั้นกับเข็มยาวของนาฬิกาทำต่อกันเมื่อเวลา {h:02d}:{m:02d} น. (ตอบมุมที่เล็กกว่า)", ang


# จัดเป็น "เรื่อง" ไม่ใช่ "ฟังก์ชัน" — ทั้งสามสดมภ์ต้องอยู่เรื่องเดียวกัน
# แต่ถ้าเรื่องนั้นมีหลายรูปแบบ ต้องใช้ *คนละรูปแบบ* กัน ไม่งั้นโจทย์จะง่ายเกินไป
#
# เทียบวงกลมรัศมี 3 / 5 / 10 = เด็กตอบได้โดยไม่ต้องคำนวณ ตัวเลขใหญ่กว่าก็ชนะ
# เทียบวงกลม / สามเหลี่ยมด้านเท่า / สี่เหลี่ยมจัตุรัส = ต้องคำนวณจริงถึงจะรู้
# ข้อสอบจริงทำแบบหลัง (TGAT2 Dek66 หน้า 9 ข้อ 28)
DOMAINS = {
    "ร้อยละ": [q_percent],
    "พื้นที่รูปเรขาคณิต": [q_circle, q_square, q_tri, q_rect],
    "ความน่าจะเป็นจากลูกเต๋า": [q_dice],
    "ตรีโกณมิติ": [q_trig],
    "มุมเข็มนาฬิกา": [q_clock],
}
DOMAIN_NAMES = list(DOMAINS)

# ปริมาณที่ "คำนวณไม่ได้" เพราะโจทย์ไม่ให้ตัวเลขมา — ใช้ทำข้อที่เฉลยคือ ไม่เพียงพอ
VAGUE = [
    "ค่ามัธยฐานของความสูงของนักเรียนห้อง ม.6/1",
    "ค่าเฉลี่ยของความสูงของนักเรียนห้อง ม.6/1",
    "พิสัยของความสูงของนักเรียนห้อง ม.6/1",
    "ค่าฐานนิยมของคะแนนสอบของนักเรียนห้อง ม.6/2",
    "ค่าเฉลี่ยของคะแนนสอบของนักเรียนห้อง ม.6/2",
    "ส่วนเบี่ยงเบนมาตรฐานของคะแนนสอบของนักเรียนห้อง ม.6/2",
]


# ============================================================
#  ตัดสินคำตอบ — จุดเดียวที่รู้ว่าโจทย์ตอบอะไร
# ============================================================

def verdict(vals):
    """คืนดัชนีคำตอบ (0-3) หรือ None ถ้าโจทย์ใช้ไม่ได้

    None แปลว่าเข้าเขตอันตราย เช่น สองสดมภ์เสมอกันที่ตำแหน่งสูงสุด
    หรือห่างกันน้อยจนบอกไม่ได้ว่าตั้งใจให้เท่าหรือให้ต่าง
    """
    a, b, c = vals
    d = [abs(a - b), abs(a - c), abs(b - c)]

    # ทุกคู่ต้องตัดสินได้ชัด ไม่เท่าก็ต่างแบบเห็นชัด ห้ามคาบเส้น
    for gap in d:
        if not (gap <= EPS_EQ or gap >= EPS_DIFF):
            return None

    eq = [g <= EPS_EQ for g in d]
    if all(eq):
        return 3                                  # เท่ากันทั้งสาม
    if any(eq):
        # มีสองตัวเท่ากัน — ใช้ได้ก็ต่อเมื่อคู่นั้น *ไม่ใช่* ตัวมากสุด
        mx = max(vals)
        if sum(1 for v in vals if abs(v - mx) <= EPS_EQ) > 1:
            return None                           # เสมอกันที่ยอด = ไม่มีคำตอบ
    mx = max(vals)
    return vals.index(mx)


def compare(rng, want=0, vague_rate=0.18):
    """คืน (rows, choices, ansIdx) โดย rows คือข้อความ 3 สดมภ์

    want = ตำแหน่งที่อยากให้เฉลยไปตก (0-4) — ตัวเลือกคงที่ เลยต้องสุ่มโจทย์จนได้เฉลยตรงช่อง
    """
    if want == 4:                                  # ข้อที่เฉลยคือ ไม่เพียงพอ
        rows = rng.sample(VAGUE, 3)
        return rows, CHOICES, 4

    for _ in range(4000):
        if rng.random() < vague_rate:
            continue
        # เลือกเรื่องก่อน แล้วค่อยเลือกรูปแบบภายในเรื่องนั้น
        # (TGAT2 Dek66 หน้า 9: ข้อ 26 ร้อยละล้วน · 27 ตรีโกณล้วน · 28 พื้นที่สามรูปทรงต่างกัน ·
        #  29 ความน่าจะเป็นสามเงื่อนไขต่างกัน · 30 ค่าสถิติสามตัวของชุดข้อมูลเดียวกัน)
        gens = DOMAINS[rng.choice(DOMAIN_NAMES)]
        picks = rng.sample(gens, 3) if len(gens) >= 3 else [rng.choice(gens) for _ in range(3)]
        made = [g(rng) for g in picks]
        rows = [t for t, _ in made]
        vals = [v for _, v in made]
        if len(set(rows)) != 3:
            continue
        v = verdict(vals)
        if v is None or v != want:
            continue
        return rows, CHOICES, want
    raise RuntimeError(f"สร้างโจทย์เปรียบเทียบเชิงปริมาณที่เฉลยตรงช่อง {want} ไม่สำเร็จ")


def build(add, part, rng, n=5, lvl=2):
    """เติมโจทย์แนวนี้เข้าคลัง — เฉลยไล่ครบทั้ง 5 ช่อง"""
    for i in range(n):
        rows, choices, idx = compare(rng, want=i % 5)
        stem = STEM + "\n" + "\n".join(f"สดมภ์ {'กขค'[k]}.  {t}" for k, t in enumerate(rows))
        add(part, "การเปรียบเทียบเชิงปริมาณ", stem, choices, idx, lvl=lvl)


# ============================================================
#  ตัวตรวจ — python compare.py
# ============================================================

if __name__ == "__main__":
    import random, sys

    bad = []
    seen_ans = set()
    for s in range(200):
        rng = random.Random(s)
        for want in range(5):
            rows, choices, idx = compare(rng, want=want)
            seen_ans.add(idx)
            if idx != want:
                bad.append(f"s={s} want={want}: เฉลยไปตกช่อง {idx}")
            if len(rows) != 3 or len(set(rows)) != 3:
                bad.append(f"s={s} want={want}: สดมภ์ซ้ำกันหรือไม่ครบสาม")
            if choices is not CHOICES:
                bad.append(f"s={s} want={want}: ตัวเลือกไม่ใช่ชุดคงที่")

    # ตรวจตัวตัดสินโดยตรงด้วยกรณีที่รู้คำตอบอยู่แล้ว
    cases = [
        ((D(3), D(2), D(1)), 0, "ก มากสุด"),
        ((D(1), D(3), D(2)), 1, "ข มากสุด"),
        ((D(1), D(2), D(3)), 2, "ค มากสุด"),
        ((D(5), D(5), D(5)), 3, "เท่ากันหมด"),
        ((D(5), D(5), D(1)), None, "เสมอกันที่ยอด ต้องตีตก"),
        ((D(1), D(5), D(5)), None, "เสมอกันที่ยอด ต้องตีตก"),
        ((D(4), D(2), D(2)), 0, "เสมอกันแต่ไม่ใช่ยอด ใช้ได้"),
        ((D(1), D(1) + D("1e-20"), D(9)), None, "ห่างกันคาบเส้น ต้องตีตก"),
    ]
    for vals, exp, why in cases:
        got = verdict(list(vals))
        if got != exp:
            bad.append(f"verdict{vals} -> {got} ควรเป็น {exp} ({why})")

    # sin60°×cos30° = (√3/2)² = 3/4 พอดี — ต้องตัดสินว่าเท่ากันทั้งสาม
    if verdict([_TRIG[(60, "sin")] * _TRIG[(30, "cos")], D(3) / 4, D(3) / 4]) != 3:
        bad.append("sin60°×cos30° ไม่ถูกตัดสินว่าเท่ากับ 3/4 — ความละเอียดไม่พอ")
    # และต้องไม่หลงว่าเท่า ทั้งที่ค่าที่สามมากกว่าจริง
    if verdict([_TRIG[(60, "sin")] * _TRIG[(30, "cos")], D(3) / 4, D(1)]) != 2:
        bad.append("ควรตอบว่าสดมภ์ ค. มากที่สุด")

    # ★ นี่คือเหตุผลที่ไฟล์นี้ใช้ Decimal ไม่ใช่ float ★
    # sin60°×cos60° กับ sin30°×cos30° เท่ากันพอดีในทางคณิตศาสตร์ (ทั้งคู่ = √3/4)
    # แต่ float ให้ 0.4330127018922194 กับ 0.4330127018922193 ต่างกันที่หลักที่ 16
    # ถ้าใช้ float โจทย์แบบนี้จะได้เฉลย "ก. มากที่สุด" แทน "เท่ากันทั้งสาม"
    # = เฉลยผิดที่หลุดถึงมือนักเรียนโดยไม่มีใครรู้
    same = [_TRIG[(60, "sin")] * _TRIG[(60, "cos")],
            _TRIG[(30, "sin")] * _TRIG[(30, "cos")],
            SQRT3 / 4]
    if verdict(same) != 3:
        bad.append("sin60°×cos60° กับ sin30°×cos30° ต้องเท่ากัน (= √3/4) แต่ตัดสินว่าต่าง")

    r = random.Random(11)
    print("ตัวอย่าง 3 ข้อ\n" + "=" * 62)
    for want in (0, 3, 4):
        rows, ch, idx = compare(r, want=want)
        for k, t in enumerate(rows):
            print(f"  สดมภ์ {'กขค'[k]}.  {t}")
        print(f"  → เฉลย {idx+1}) {ch[idx]}\n" + "-" * 62)

    print()
    if bad:
        for m in bad[:12]:
            print("[พัง]", m)
        print(f"พบปัญหา {len(bad)} จุด")
        sys.exit(1)
    print(f"ตรวจผ่าน 1000 ข้อ + ตัวตัดสิน 11 กรณี · เฉลยไปตกครบทุกช่อง {sorted(seen_ans)}")
